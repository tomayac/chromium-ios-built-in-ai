// Writes the prompts of the task API polyfills (Summarizer, Writer, Rewriter,
// Translator) as a C++ header, for the build of Chromium with Blink, which
// serves those APIs natively and should prompt the models as the polyfills
// do.
//
//   WEB_AI_DEMOS=/path/to/web-ai-demos node generate-task-prompts.mjs \
//       /path/to/chromium/src
//
// Every combination of options is rendered once by the polyfills' own prompt
// builders, with "{{LANGUAGE}}" for the output language's name, which the
// browser fills in.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const demos = process.env.WEB_AI_DEMOS;
const chromium = process.argv[2];
if (!demos || !chromium) {
  console.error('usage: WEB_AI_DEMOS=... node generate-task-prompts.mjs <chromium/src>');
  process.exit(1);
}
const polyfills = join(demos, 'built-in-ai-task-apis-polyfills');
const load = async (file) => import(pathToFileURL(join(polyfills, file)).href);
const { SummarizerPromptBuilder } = await load('summarizer-prompt-builder.js');
const { WriterPromptBuilder } = await load('writer-prompt-builder.js');
const { RewriterPromptBuilder } = await load('rewriter-prompt-builder.js');
const { TranslatorPromptBuilder } = await load('translator-prompt-builder.js');
console.debug = () => {};

const LANGUAGE = '{{LANGUAGE}}';

// The system prompts for every combination of `axes`, without and with the
// context instructions.
function render(Builder, axes) {
  const prompts = {};
  const keys = Object.keys(axes);
  const combine = (index, options) => {
    if (index === keys.length) {
      const key = keys.map((k) => options[k]).join('|');
      const system = (sharedContext) => {
        const builder = new Builder({ ...options, sharedContext });
        builder.getLanguageName = () => LANGUAGE;
        return builder.buildPrompt('').systemPrompt;
      };
      prompts[key] = { system: system(''), systemWithContext: system('x') };
      return;
    }
    for (const value of axes[keys[index]]) {
      combine(index + 1, { ...options, [keys[index]]: value });
    }
  };
  combine(0, {});
  return prompts;
}

const translator = new TranslatorPromptBuilder('', '').buildPrompt('');
const data = {
  summarizer: render(SummarizerPromptBuilder, {
    type: ['tldr', 'key-points', 'teaser', 'headline'],
    format: ['plain-text', 'markdown'],
    length: ['short', 'medium', 'long'],
  }),
  writer: render(WriterPromptBuilder, {
    tone: ['formal', 'neutral', 'casual'],
    format: ['plain-text', 'markdown'],
    length: ['short', 'medium', 'long'],
  }),
  rewriter: render(RewriterPromptBuilder, {
    tone: ['as-is', 'more-formal', 'more-casual'],
    format: ['as-is', 'plain-text', 'markdown'],
    length: ['as-is', 'shorter', 'longer'],
  }),
  translator: {
    system: translator.systemPrompt,
    examples: translator.initialPrompts,
  },
};

const json = JSON.stringify(data);
if (json.includes(')json"')) {
  throw new Error('The prompts contain the raw string delimiter.');
}
const header = `// Copyright 2026 The Chromium Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Generated by generate-task-prompts.mjs from the task API polyfills of
// https://github.com/GoogleChromeLabs/web-ai-demos. Do not edit.

#ifndef IOS_CHROME_BROWSER_BUILT_IN_AI_MODEL_BLINK_TASK_PROMPTS_H_
#define IOS_CHROME_BROWSER_BUILT_IN_AI_MODEL_BLINK_TASK_PROMPTS_H_

namespace built_in_ai {

// The system prompts of Summarizer, Writer, and Rewriter by
// "<option>|<option>|<option>", without and with the context instructions,
// and Translator's system prompt and examples.
inline constexpr char kTaskPromptsJson[] = R"json(${json})json";

}  // namespace built_in_ai

#endif  // IOS_CHROME_BROWSER_BUILT_IN_AI_MODEL_BLINK_TASK_PROMPTS_H_
`;
const out = join(chromium, 'ios/chrome/browser/built_in_ai/model/blink/task_prompts.h');
writeFileSync(out, header);
console.log(
  `Wrote ${out}: ${Object.keys(data.summarizer).length} summarizer, ` +
    `${Object.keys(data.writer).length} writer, ${Object.keys(data.rewriter).length} rewriter prompts, ` +
    `${json.length} bytes.`,
);
